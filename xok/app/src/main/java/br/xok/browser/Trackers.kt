    fun isTracker(host: String?): Boolean {
        if (host == null) return false
        var h = host.trimEnd('.').lowercase()
        while (true) {
            if (h in domains) return true
            val dot = h.indexOf('.')
            if (dot < 0) return false
            h = h.substring(dot + 1)
        }
    }
